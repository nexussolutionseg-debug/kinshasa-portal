-- =============================================================================
-- Place pages + Prospects (restaurants & hotels lead flow). (2026-11-10)
-- Safe to run more than once. Nothing is deleted.
--
-- WHAT THIS CHANGES (plain English)
--   1. `places` gets five optional fields shown on each place's own page:
--      website, instagram, facebook, whatsapp, hours (opening hours, free text).
--   2. `events` gets an optional `place_id`: an event can be attached to a
--      place, and then shows on that place's page.
--   3. New table `kl_leads` (Backoffice → Prospects): restaurants and hotels
--      to contact, with their status, next action, contacts and map position.
--      ONLY team accounts (kl_admins) can see or change it; visitors can't
--      read it at all. When a prospect is put on the map, it becomes a place
--      and `place_id` points to it.
-- =============================================================================
begin;

-- 1. Place page fields -------------------------------------------------------
alter table public.places add column if not exists website   text;
alter table public.places add column if not exists instagram text;
alter table public.places add column if not exists facebook  text;
alter table public.places add column if not exists whatsapp  text;
alter table public.places add column if not exists hours     text;

-- 2. Event → place -----------------------------------------------------------
alter table public.events add column if not exists place_id bigint references public.places(id) on delete set null;
create index if not exists events_place_id_idx on public.events(place_id);

-- 3. Prospects ---------------------------------------------------------------
create table if not exists public.kl_leads (
  id          bigint generated by default as identity primary key,
  name        text not null,
  commune     text,
  kind        text not null default 'restauration' check (kind in ('restauration', 'hebergement', 'sortie', 'commerce', 'autre')),
  place_type  text,
  cuisine     text,
  address     text,
  lat         double precision,
  lng         double precision,
  phone       text,
  email       text,
  website     text,
  instagram   text,
  facebook    text,
  source      text default 'OpenStreetMap',
  status      text not null default 'nouveau' check (status in ('nouveau', 'contacte', 'interesse', 'proposition', 'partenaire', 'refuse')),
  pack        text check (pack in ('page', 'site', 'site_reseaux')),
  next_action text,
  next_date   date,
  owner       text,
  notes       text,
  place_id    bigint references public.places(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  created_by  uuid default auth.uid()
);
create index if not exists kl_leads_status_idx on public.kl_leads(status);
create unique index if not exists kl_leads_name_commune_key on public.kl_leads (lower(name), lower(coalesce(commune, '')));

create or replace function public.kl_leads_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists kl_leads_touch on public.kl_leads;
create trigger kl_leads_touch before update on public.kl_leads for each row execute function public.kl_leads_touch();

alter table public.kl_leads enable row level security;
revoke all on public.kl_leads from anon, authenticated;
grant select, insert, update, delete on public.kl_leads to authenticated;
grant usage on sequence public.kl_leads_id_seq to authenticated;

drop policy if exists "team read"   on public.kl_leads;
drop policy if exists "team insert" on public.kl_leads;
drop policy if exists "team update" on public.kl_leads;
drop policy if exists "team delete" on public.kl_leads;
create policy "team read"   on public.kl_leads for select to authenticated using (public.is_kl_admin());
create policy "team insert" on public.kl_leads for insert to authenticated with check (public.is_kl_admin());
create policy "team update" on public.kl_leads for update to authenticated using (public.is_kl_admin()) with check (public.is_kl_admin());
create policy "team delete" on public.kl_leads for delete to authenticated using (public.is_kl_admin());

commit;

select 'places (site, réseaux, horaires) + events.place_id + kl_leads ✔' as statut;
